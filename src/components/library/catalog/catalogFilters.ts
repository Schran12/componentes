export type SectionFilter = (typeof topicFilters)[number]['id']

export function matchesSectionFilter(component: CatalogComponent, filter: SectionFilter) {
  if (filter === 'all') return true

  const selected = topicFilters.find((item) => item.id === filter)
  if (!selected) return true

  return (
    ('prefixes' in selected &&
      selected.prefixes.some((prefix) => component.id.startsWith(prefix))) ||
    ('componentIds' in selected && selected.componentIds.includes(component.id as never))
  )
}
