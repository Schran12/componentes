export function getLayoutRecipe(id: string) {
  return layoutRecipes.find((recipe) => recipe.id === id)
}

/**
 * Evita duas barras de contato: `navbar-accent` já tem topbar.
 * Também útil se o registry/cache ainda listar o par antigo.
 */
export function normalizeRecipeComponents(components: readonly string[]) {
  const hasNavbarAccent = components.includes('navbar-accent')
  if (!hasNavbarAccent) return [...components]
  return components.filter((id) => id !== 'contact-info-bar')
}

